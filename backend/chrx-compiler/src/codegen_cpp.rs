use crate::ast::*;
use std::fmt::Write;

pub struct CppGenerator {
    output: String,
}

impl CppGenerator {
    pub fn new() -> Self {
        Self {
            output: String::new(),
        }
    }

    pub fn generate(&mut self, mission: &Mission) -> Result<String, std::fmt::Error> {
        writeln!(self.output, "// Generated by Interlock DSL Compiler (.chrxxx)")?;
        writeln!(self.output, "// Target: M4 Pro (48GB Unified Memory)")?;
        writeln!(self.output, "#pragma once")?;
        writeln!(self.output, "#include <cstdint>")?;
        writeln!(self.output, "#include <cstddef>")?;
        writeln!(self.output, "#include <array>")?;
        writeln!(self.output, "")?;

        writeln!(self.output, "namespace chrx::generated::{} {{", mission.name.replace(" ", "_"))?;

        self.gen_strict_limits(&mission.strict_limits)?;
        self.gen_resources(&mission.resources)?;
        self.gen_choreographies(&mission.choreographies)?;

        writeln!(self.output, "}} // namespace chrx::generated")?;

        Ok(self.output.clone())
    }

    fn gen_strict_limits(&mut self, limits: &[StrictLimit]) -> Result<(), std::fmt::Error> {
        writeln!(self.output, "    namespace hardware_constraints {{")?;
        for limit in limits {
            let const_name = limit.key.replace(".", "_").to_uppercase();
            // Simple parsing of value for constexpr, e.g., "82C" -> 82
            let numeric_value = limit.value.chars().filter(|c| c.is_digit(10)).collect::<String>();
            writeln!(self.output, "        static constexpr int32_t LIMIT_{} = {}; // {}", const_name, numeric_value, limit.value)?;
        }
        writeln!(self.output, "    }}")?;
        writeln!(self.output, "")?;
        Ok(())
    }

    fn gen_resources(&mut self, resources: &[Resource]) -> Result<(), std::fmt::Error> {
        writeln!(self.output, "    namespace resources {{")?;
        for res in resources {
            let size_bytes = self.parse_size(&res.size);
            writeln!(self.output, "        struct alignas({}) {} {{", res.alignment, res.name)?;
            writeln!(self.output, "            static constexpr size_t SIZE = {};", size_bytes)?;
            writeln!(self.output, "            static constexpr const char* TYPE = \"{}\";", res.r_type)?;
            writeln!(self.output, "            uint8_t* data; // Mapped to ABB")?;
            writeln!(self.output, "        }};")?;
        }
        writeln!(self.output, "    }}")?;
        writeln!(self.output, "")?;
        Ok(())
    }

    fn gen_choreographies(&mut self, choreos: &[Choreography]) -> Result<(), std::fmt::Error> {
        for choreo in choreos {
            let enum_name = format!("{}Phase", choreo.name);
            writeln!(self.output, "    enum class {} : uint8_t {{", enum_name)?;
            for phase in &choreo.phases {
                writeln!(self.output, "        {},", phase.name.to_uppercase())?;
            }
            writeln!(self.output, "    }};")?;
            writeln!(self.output, "")?;

            writeln!(self.output, "    inline void execute_{}({} phase) {{", choreo.name.to_lowercase(), enum_name)?;
            writeln!(self.output, "        switch(phase) {{")?;
            for phase in &choreo.phases {
                writeln!(self.output, "            [[likely]] case {}::{}: {{", enum_name, phase.name.to_uppercase())?;
                for cmd in &phase.commands {
                    self.gen_command(cmd)?;
                }
                writeln!(self.output, "                break;")?;
                writeln!(self.output, "            }}")?;
            }
            writeln!(self.output, "        }}")?;
            writeln!(self.output, "    }}")?;
        }
        Ok(())
    }

    fn gen_command(&mut self, cmd: &ChrxCommand) -> Result<(), std::fmt::Error> {
        match cmd {
            ChrxCommand::Bind(s) => writeln!(self.output, "                // bind {}", s)?,
            ChrxCommand::Await(s) => writeln!(self.output, "                // await {}", s)?,
            ChrxCommand::Lock(s) => writeln!(self.output, "                // lock({})", s)?,
            ChrxCommand::Assert(s) => writeln!(self.output, "                // assert {}", s)?,
            ChrxCommand::Purge(s) => writeln!(self.output, "                // purge {}", s)?,
            ChrxCommand::Call(s) => writeln!(self.output, "                // call {}", s)?,
            ChrxCommand::Halt(s) => writeln!(self.output, "                // halt {}", s)?,
            ChrxCommand::Commit(s) => writeln!(self.output, "                // commit {}", s)?,
            ChrxCommand::Resume(s) => writeln!(self.output, "                // resume {}", s)?,
        }
        Ok(())
    }

    fn parse_size(&self, size: &str) -> u64 {
        let numeric: String = size.chars().filter(|c| c.is_digit(10)).collect();
        let val: u64 = numeric.parse().unwrap_or(0);
        if size.contains("GB") { val * 1024 * 1024 * 1024 }
        else if size.contains("MB") { val * 1024 * 1024 }
        else if size.contains("KB") { val * 1024 }
        else { val }
    }
}
